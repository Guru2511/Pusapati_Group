  id, COALESCE(payload->>'full_name', ''), COALESCE(payload->>'phone', ''),
  COALESCE(payload->>'email', ''), COALESCE(payload->>'role', ''),
  COALESCE(payload->>'department', ''), COALESCE(payload->>'experience', ''),
