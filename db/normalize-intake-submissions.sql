CREATE TABLE IF NOT EXISTS career_applications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legacy_id bigint UNIQUE,
  full_name text NOT NULL DEFAULT '',
  phone text NOT NULL DEFAULT '',
  email text NOT NULL DEFAULT '',
  role text NOT NULL DEFAULT '',
  department text NOT NULL DEFAULT '',
  experience text NOT NULL DEFAULT '',
  portfolio_url text NOT NULL DEFAULT '',
  cover_note text NOT NULL DEFAULT '',
  is_internship boolean NOT NULL DEFAULT false,
  status text NOT NULL DEFAULT 'new',
  assigned_to text NOT NULL DEFAULT '',
  notes jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(notes) = 'array'),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS investor_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legacy_id bigint UNIQUE,
  full_name text NOT NULL DEFAULT '',
  email text NOT NULL DEFAULT '',
  phone text NOT NULL DEFAULT '',
  organisation text NOT NULL DEFAULT '',
  investor_type text NOT NULL DEFAULT '',
  areas_of_interest text NOT NULL DEFAULT '',
  message text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'new',
  assigned_to text NOT NULL DEFAULT '',
  notes jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(notes) = 'array'),
  created_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO quote_enquiries (
  legacy_id, name, phone, email, company, category, location, interest, quantity, timeline,
  pour_date, pour_time, pump_required, incoterms, requirement, source_page,
  status, assigned_to, notes, created_at
)
SELECT
  id, COALESCE(payload->>'name', ''), COALESCE(payload->>'phone', ''),
  COALESCE(payload->>'email', ''), COALESCE(payload->>'company', ''),
  COALESCE(payload->>'category', ''), COALESCE(payload->>'location', ''),
  COALESCE(payload->>'interest', ''), COALESCE(payload->>'quantity', ''),
  COALESCE(payload->>'timeline', ''), COALESCE(payload->>'pour_date', ''),
  COALESCE(payload->>'pour_time', ''), COALESCE(payload->>'pump_required', 'unsure'),
  COALESCE(payload->>'incoterms', ''), COALESCE(payload->>'requirement', ''),
  COALESCE(payload->>'source_page', ''), COALESCE(status, 'new'),
  COALESCE(assigned_to, ''), COALESCE(notes, '[]'::jsonb), created_at
FROM intake_submissions
WHERE submission_type = 'enquiry'
  AND COALESCE(payload->>'source_page', '') <> '/contact'
ON CONFLICT (legacy_id) DO NOTHING;

INSERT INTO quote_enquiry_items (
  enquiry_id, item_order, category, location, interest, quantity, timeline,
  pour_date, pour_time, pump_required, incoterms, requirement
)
SELECT
  enquiry.id,
  item.ordinality::integer,
  COALESCE(item.value->>'category', legacy.payload->>'category', ''),
  COALESCE(item.value->>'location', ''),
  COALESCE(item.value->>'interest', ''),
  COALESCE(item.value->>'quantity', ''),
  COALESCE(item.value->>'timeline', ''),
  COALESCE(item.value->>'pour_date', ''),
  COALESCE(item.value->>'pour_time', ''),
  COALESCE(item.value->>'pump_required', 'unsure'),
  COALESCE(item.value->>'incoterms', ''),
  COALESCE(item.value->>'requirement', '')
FROM intake_submissions AS legacy
CROSS JOIN LATERAL (
  SELECT id FROM quote_enquiries WHERE legacy_id = legacy.id
) AS enquiry
CROSS JOIN LATERAL jsonb_array_elements(
  CASE
    WHEN jsonb_typeof(legacy.payload->'requirement_items') = 'array'
      AND jsonb_array_length(legacy.payload->'requirement_items') > 0
    THEN legacy.payload->'requirement_items'
    ELSE jsonb_build_array(jsonb_build_object(
      'category', legacy.payload->>'category',
      'location', legacy.payload->>'location',
      'interest', legacy.payload->>'interest',
      'quantity', legacy.payload->>'quantity',
      'timeline', legacy.payload->>'timeline',
      'pour_date', legacy.payload->>'pour_date',
      'pour_time', legacy.payload->>'pour_time',
      'pump_required', legacy.payload->>'pump_required',
      'incoterms', legacy.payload->>'incoterms',
      'requirement', legacy.payload->>'requirement'
    ))
  END
) WITH ORDINALITY AS item(value, ordinality)
WHERE legacy.submission_type = 'enquiry'
  AND COALESCE(legacy.payload->>'source_page', '') <> '/contact'
ON CONFLICT (enquiry_id, item_order) DO NOTHING;

INSERT INTO contact_messages (
  legacy_id, name, phone, email, company, requirement, source_page,
  status, assigned_to, notes, created_at
)
SELECT
  id, COALESCE(payload->>'name', ''), COALESCE(payload->>'phone', ''),
  COALESCE(payload->>'email', ''), COALESCE(payload->>'company', ''),
  COALESCE(payload->>'requirement', ''), COALESCE(payload->>'source_page', ''),
