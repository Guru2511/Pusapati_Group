BEGIN;

CREATE TABLE IF NOT EXISTS quote_enquiries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legacy_id bigint UNIQUE,
  name text NOT NULL DEFAULT '',
  phone text NOT NULL DEFAULT '',
  email text NOT NULL DEFAULT '',
  company text NOT NULL DEFAULT '',
  category text NOT NULL DEFAULT '',
  location text NOT NULL DEFAULT '',
  interest text NOT NULL DEFAULT '',
  quantity text NOT NULL DEFAULT '',
  timeline text NOT NULL DEFAULT '',
  pour_date text NOT NULL DEFAULT '',
  pour_time text NOT NULL DEFAULT '',
  pump_required text NOT NULL DEFAULT 'unsure',
  incoterms text NOT NULL DEFAULT '',
  requirement text NOT NULL DEFAULT '',
  source_page text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'new',
  assigned_to text NOT NULL DEFAULT '',
  notes jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(notes) = 'array'),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS quote_enquiry_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enquiry_id bigint NOT NULL REFERENCES quote_enquiries(id),
  item_order integer NOT NULL,
  category text NOT NULL DEFAULT '',
  location text NOT NULL DEFAULT '',
  interest text NOT NULL DEFAULT '',
  quantity text NOT NULL DEFAULT '',
  timeline text NOT NULL DEFAULT '',
  pour_date text NOT NULL DEFAULT '',
  pour_time text NOT NULL DEFAULT '',
  pump_required text NOT NULL DEFAULT 'unsure',
  incoterms text NOT NULL DEFAULT '',
  requirement text NOT NULL DEFAULT '',
  UNIQUE (enquiry_id, item_order)
);

CREATE TABLE IF NOT EXISTS contact_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legacy_id bigint UNIQUE,
  name text NOT NULL DEFAULT '',
  phone text NOT NULL DEFAULT '',
  email text NOT NULL DEFAULT '',
  company text NOT NULL DEFAULT '',
  requirement text NOT NULL DEFAULT '',
  source_page text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'new',
  assigned_to text NOT NULL DEFAULT '',
  notes jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(notes) = 'array'),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS vendor_applications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legacy_id bigint UNIQUE,
  company_name text NOT NULL DEFAULT '',
  contact_name text NOT NULL DEFAULT '',
  phone text NOT NULL DEFAULT '',
  email text NOT NULL DEFAULT '',
  category text NOT NULL DEFAULT '',
  city text NOT NULL DEFAULT '',
  gstin text NOT NULL DEFAULT '',
  website text NOT NULL DEFAULT '',
  years_in_business text NOT NULL DEFAULT '',
  description text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'new',
  assigned_to text NOT NULL DEFAULT '',
  notes jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(notes) = 'array'),
  created_at timestamptz NOT NULL DEFAULT now()
